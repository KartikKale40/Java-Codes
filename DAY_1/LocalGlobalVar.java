public class LocalGlobalVar {
    
    static int a;
    static long b;
    static char c;
    static String d;
    static boolean e;

    public static void main(String[] args) {
       
        System.out.println(a);
        System.out.println(b);
        System.out.println((int) c); 
        System.out.println(d);
        System.out.println(e);
    }
}
